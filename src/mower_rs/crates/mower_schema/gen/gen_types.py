#!/usr/bin/env python3
"""Writes the plain Rust message types from mower_schema's committed files (E9-22).

    python3 src/mower_rs/crates/mower_schema/gen/gen_types.py          # writes
    python3 src/mower_rs/crates/mower_schema/gen/gen_types.py --check  # fails if they differ

gen_schema.py copied the interface files from the robot image; this reads only
those, so it needs no ROS. It writes:

- `mower_msgs/src/generated/<pkg>.rs`: one struct per message and per part of a
  service or action, in r2r's module layout (`std_msgs::msg::String`,
  `std_srvs::srv::Trigger::{Service, Request, Response}`,
  `mower_interface::action::Waypoint::{Action, Goal, Result, Feedback,
  FeedbackMessage, SendGoal::{..}, GetResult::{..}}`), with what r2r_msg_gen 0.9.7 gives
  a type: the same derives, `#[serde(default)]`, a `Vec` for every array (fixed ones
  included), `#[serde(rename)]` for a Rust keyword, an empty struct for an empty message
  and a `Default` holding the `.msg` file's defaults and each fixed array's length.
  One difference: a constant has its field's type here, where r2r's is a bindgen enum.
- `mower_msgs/src/generated/mod.rs`: the modules, and the macros that list them.
- `mower_msgs_ros/src/generated.rs`: `RosMirror`, `ServiceMirror`, `ActionMirror`, the
  moves between a plain type and r2r's (the bridge's `ros` feature, later).

The r2r side of the proof is `mower_msgs_ros/tests/parity.rs`, the no-ROS side
`mower_ros_facts/tests/plain_*.rs`. A form of `.msg` line this does not know stops it:
no guessing.

Stdlib only.
"""
import os
import re
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
SCHEMA = os.path.dirname(HERE)
CRATES = os.path.dirname(SCHEMA)
PLAIN = os.path.join(CRATES, 'mower_msgs', 'src', 'generated')
MIRROR = os.path.join(CRATES, 'mower_msgs_ros', 'src', 'generated.rs')

HEADER = '// @generated by mower_schema/gen/gen_types.py from mower_schema/{msg,srv,action}: do not edit.\n'

PRIMITIVES = {
    'bool': 'bool', 'byte': 'u8', 'char': 'u8', 'float32': 'f32', 'float64': 'f64', 'int8': 'i8', 'uint8': 'u8',
    'int16': 'i16', 'uint16': 'u16', 'int32': 'i32', 'uint32': 'u32', 'int64': 'i64', 'uint64': 'u64',
}
STRING = 'std::string::String'
# r2r_msg_gen's rust_mangle (bindgen's list): a field of one of these names gets a `_`.
KEYWORDS = set('''abstract alignof as async await become box break const continue crate do dyn else enum extern false
final fn for if impl in let loop macro match mod move mut offsetof override priv proc pub pure ref return Self self
sizeof static struct super trait true try type typeof unsafe unsized use virtual where while yield str bool f32 f64
usize isize u128 i128 u64 i64 u32 i32 u16 i16 u8 i8 _'''.split())


class Field:
    def __init__(self, name, base, array, nested, default):
        self.name = name
        self.base = base  # the Rust element type
        self.array = array  # None, ('fixed', n), ('seq',), ('bounded', n)
        self.nested = nested  # for a message, its plain path below the crate root
        self.default = default  # a Rust expression, or None


class Msg:
    def __init__(self, ros_name, path, rust_name, fields, constants):
        self.ros_name = ros_name  # pkg/srv/Trigger_Request
        self.path = path  # ('std_srvs', 'srv', 'Trigger', 'Request')
        self.rust_name = rust_name
        self.fields = fields
        self.constants = constants


def fail(where, line, why):
    raise SystemExit(f'{where}: {line!r}: {why}')


def uncomment(line, where):
    head = line.split('#', 1)[0]
    if '"' in head or "'" in head:
        fail(where, line, 'a quoted value: none in the table so far, and this generator does not read them')
    return head.strip()


def default_value(base, text, where):
    text = text.strip()
    if base == 'bool' and text in ('true', 'false'):
        return text
    if base in ('f32', 'f64') and re.fullmatch(r'-?\d+(\.\d+)?', text):
        return text if '.' in text else text + '.0'
    if base in PRIMITIVES.values() and base not in ('bool', 'f32', 'f64') and re.fullmatch(r'-?\d+', text):
        return text
    fail(where, text, f'a default of {base} this generator does not read')


def message_path(pkg, base):
    parts = base.split('/')
    if len(parts) == 1:
        return (pkg, 'msg', parts[0])
    if len(parts) == 2:
        return (parts[0], 'msg', parts[1])
    if len(parts) == 3 and parts[1] == 'msg':
        return (parts[0], 'msg', parts[2])
    raise SystemExit(f'a type name this generator does not read: {base}')


def parse_section(text, pkg, where):
    """A `.msg` file or one section of a `.srv` or `.action` file."""
    fields, constants = [], []
    for raw in text.split('\n'):
        line = uncomment(raw, where)
        if not line:
            continue
        m = re.fullmatch(r'(\S+)\s+([A-Za-z][A-Za-z0-9_]*)\s*=\s*(\S+)', line)
        if m:
            ty, name, value = m.groups()
            if ty not in PRIMITIVES or ty == 'bool' or ty.startswith('float'):
                fail(where, line, 'a constant of a type none in the table has')
            if not re.fullmatch(r'-?\d+', value):
                fail(where, line, 'not an integer')
            constants.append((name, PRIMITIVES[ty], value))
            continue
        m = re.fullmatch(r'(\S+)\s+([A-Za-z][A-Za-z0-9_]*)(?:\s+(\S.*))?', line)
        if not m:
            fail(where, line, 'neither a field nor a constant')
        ty, name, default = m.groups()
        array = None
        a = re.fullmatch(r'([^\[\]]+)\[(.*)\]', ty)
        if a:
            ty, inner = a.groups()
            if inner == '':
                array = ('seq',)
            elif inner.startswith('<='):
                array = ('bounded', int(inner[2:]))
            else:
                array = ('fixed', int(inner))
        nested = None
        if ty in PRIMITIVES:
            base = PRIMITIVES[ty]
        elif ty == 'string' or re.fullmatch(r'string<=\d+', ty):
            base = STRING
        elif ty.startswith('wstring'):
            fail(where, line, 'no wstring in the table so far: mower_cdr does not support one')
        else:
            nested = message_path(pkg, ty)
            base = None
        if default is not None and (array or nested or base == STRING):
            fail(where, line, 'a default this generator does not read')
        fields.append(Field(name, base, array, nested, default_value(base, default, where) if default else None))
    return fields, constants


def sections(text, where, count):
    out, current = [], []
    for line in text.split('\n'):
        if line.rstrip() == '---':
            out.append('\n'.join(current))
            current = []
        else:
            current.append(line)
    out.append('\n'.join(current))
    if len(out) != count:
        raise SystemExit(f'{where}: {len(out)} sections, not {count}')
    return out


def read(path):
    with open(path, encoding='utf-8') as f:
        return f.read()


def listing(kind, ext):
    root = os.path.join(SCHEMA, kind)
    for pkg in sorted(os.listdir(root)):
        pkg_dir = os.path.join(root, pkg)
        if os.path.isdir(pkg_dir):
            for f in sorted(os.listdir(pkg_dir)):
                if f.endswith(ext):
                    yield pkg, f[:-len(ext)], os.path.join(pkg_dir, f)


def single(name, base, nested=None):
    return Field(name, base, None, nested, None)


def load():
    msgs, services, actions = [], [], []
    for pkg, name, path in listing('msg', '.msg'):
        fields, constants = parse_section(read(path), pkg, path)
        msgs.append(Msg(f'{pkg}/msg/{name}', (pkg, 'msg', name), name, fields, constants))
    for pkg, name, path in listing('srv', '.srv'):
        text = sections(read(path), path, 2)
        part = []
        for i, (suffix, rust) in enumerate((('_Request', 'Request'), ('_Response', 'Response'))):
            fields, constants = parse_section(text[i], pkg, path)
            part.append(Msg(f'{pkg}/srv/{name}{suffix}', (pkg, 'srv', name, rust), rust, fields, constants))
        services.append((pkg, name, part))
    for pkg, name, path in listing('action', '.action'):
        text = sections(read(path), path, 3)
        base = (pkg, 'action', name)
        uuid = ('unique_identifier_msgs', 'msg', 'UUID')
        time = ('builtin_interfaces', 'msg', 'Time')
        part = {}
        for i, rust in enumerate(('Goal', 'Result', 'Feedback')):
            fields, constants = parse_section(text[i], pkg, path)
            part[rust] = Msg(f'{pkg}/action/{name}_{rust}', base + (rust,), rust, fields, constants)
        ros = f'{pkg}/action/{name}'
        part['FeedbackMessage'] = Msg(f'{ros}_FeedbackMessage', base + ('FeedbackMessage',), 'FeedbackMessage',
                                      [single('goal_id', None, uuid), single('feedback', None, base + ('Feedback',))], [])
        send = (Msg(f'{ros}_SendGoal_Request', base + ('SendGoal', 'Request'), 'Request',
                    [single('goal_id', None, uuid), single('goal', None, base + ('Goal',))], []),
                Msg(f'{ros}_SendGoal_Response', base + ('SendGoal', 'Response'), 'Response',
                    [single('accepted', 'bool'), single('stamp', None, time)], []))
        get = (Msg(f'{ros}_GetResult_Request', base + ('GetResult', 'Request'), 'Request',
                   [single('goal_id', None, uuid)], []),
               Msg(f'{ros}_GetResult_Response', base + ('GetResult', 'Response'), 'Response',
                   [single('status', 'i8'), single('result', None, base + ('Result',))], []))
        actions.append((pkg, name, part, send, get))
    return msgs, services, actions


def rust_field(name):
    return name + '_' if name in KEYWORDS else name


def field_type(f):
    elem = 'crate::' + '::'.join(f.nested) if f.nested else f.base
    return f'Vec<{elem}>' if f.array else elem


def default_expr(f):
    if f.array and f.array[0] == 'fixed':
        return f'vec![Default::default(); {f.array[1]}]'
    if f.array:
        return 'Vec::new()'
    return f.default if f.default else 'Default::default()'


def plain_struct(m, indent):
    pad = ' ' * indent
    out = [f'{pad}/// `{m.ros_name}`',
           f'{pad}#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]',
           f'{pad}#[serde(default)]']
    fields = m.fields
    if not fields:
        out.append(f'{pad}pub struct {m.rust_name} {{}}')
    else:
        out.append(f'{pad}pub struct {m.rust_name} {{')
        for f in fields:
            if rust_field(f.name) != f.name:
                out.append(f'{pad}    #[serde(rename = "{f.name}")]')
            out.append(f'{pad}    pub {rust_field(f.name)}: {field_type(f)},')
        out.append(f'{pad}}}')
    out.append(f'{pad}impl Default for {m.rust_name} {{')
    out.append(f'{pad}    fn default() -> Self {{')
    if not fields:
        out.append(f'{pad}        Self {{}}')
    else:
        out.append(f'{pad}        Self {{')
        for f in fields:
            out.append(f'{pad}            {rust_field(f.name)}: {default_expr(f)},')
        out.append(f'{pad}        }}')
    out.append(f'{pad}    }}')
    out.append(f'{pad}}}')
    out.append(f'{pad}impl crate::MessageType for {m.rust_name} {{')
    out.append(f'{pad}    const NAME: &\'static str = "{m.ros_name}";')
    out.append(f'{pad}}}')
    if m.constants:
        out.append(f'{pad}impl {m.rust_name} {{')
        for name, ty, value in m.constants:
            out.append(f'{pad}    pub const {name}: {ty} = {value};')
        out.append(f'{pad}}}')
    return out


def plain_service_marker(ros, pad):
    return [f'{pad}/// `{ros}`',
            f'{pad}#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]',
            f'{pad}pub struct Service();',
            f'{pad}impl crate::ServiceType for Service {{',
            f'{pad}    type Request = Request;',
            f'{pad}    type Response = Response;',
            f'{pad}    const NAME: &\'static str = "{ros}";',
            f'{pad}}}']


def plain_package(pkg, msgs, services, actions):
    out = [HEADER.rstrip('\n')]
    if msgs:
        out += ['pub mod msg {', '    use serde::{Deserialize, Serialize};']
        for m in msgs:
            out.append('')
            out += plain_struct(m, 4)
        out.append('}')
    if services:
        out += ['pub mod srv {']
        for i, (_pkg, name, part) in enumerate(services):
            if i:
                out.append('')
            out += ['    #[allow(non_snake_case)]', f'    pub mod {name} {{', '        use serde::{Deserialize, Serialize};', '']
            out += plain_service_marker(f'{pkg}/srv/{name}', ' ' * 8)
            for m in part:
                out.append('')
                out += plain_struct(m, 8)
            out.append('    }')
        out.append('}')
    if actions:
        out += ['pub mod action {']
        for i, (_pkg, name, part, send, get) in enumerate(actions):
            if i:
                out.append('')
            ros = f'{pkg}/action/{name}'
            out += ['    #[allow(non_snake_case)]', f'    pub mod {name} {{', '        use serde::{Deserialize, Serialize};', '',
                    f'        /// `{ros}`',
                    '        #[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]',
                    '        pub struct Action();',
                    '        impl crate::ActionType for Action {',
                    '            type Goal = Goal;',
                    '            type Result = Result;',
                    '            type Feedback = Feedback;',
                    '            type FeedbackMessage = FeedbackMessage;',
                    '            type SendGoal = SendGoal::Service;',
                    '            type GetResult = GetResult::Service;',
                    f'            const NAME: &\'static str = "{ros}";',
                    '        }']
            for rust in ('Goal', 'Result', 'Feedback', 'FeedbackMessage'):
                out.append('')
                out += plain_struct(part[rust], 8)
            for mod, pair in (('SendGoal', send), ('GetResult', get)):
                out += ['', '        #[allow(non_snake_case)]', f'        pub mod {mod} {{',
                        '            use serde::{Deserialize, Serialize};', '']
                out += plain_service_marker(f'{ros}_{mod}', ' ' * 12)
                for m in pair:
                    out.append('')
                    out += plain_struct(m, 12)
                out.append('        }')
            out.append('    }')
        out.append('}')
    return '\n'.join(out) + '\n'


def macro(name, doc, rows):
    out = [f'/// {doc}', '#[macro_export]', f'macro_rules! {name} {{', '    ($callback:ident) => {', '        $callback! {']
    out += [f'            {row}' for row in rows]
    out += ['        }', '    };', '}']
    return out


def every_message(msgs, services, actions):
    all_msgs = list(msgs)
    for _p, _n, part in services:
        all_msgs += part
    for _p, _n, part, send, get in actions:
        all_msgs += [part[r] for r in ('Goal', 'Result', 'Feedback', 'FeedbackMessage')] + list(send) + list(get)
    return sorted(all_msgs, key=lambda m: m.ros_name)


def plain_mod(pkgs, all_msgs, services, actions):
    out = [HEADER.rstrip('\n'), '']
    out += [f'pub mod {p};' for p in pkgs]
    out.append('')
    out += macro('for_each_message', 'Calls `$callback! { "pkg/kind/Name" => pkg::kind::Name; ... }` with every message type here.',
                 [f'"{m.ros_name}" => {"::".join(m.path)};' for m in all_msgs])
    out.append('')
    srv_rows = [f'"{p}/srv/{n}" => {p}::srv::{n};' for p, n, _ in sorted(services, key=lambda s: s[:2])]
    out += macro('for_each_service', 'Calls `$callback! { "pkg/srv/Name" => pkg::srv::Name; ... }` with every service here.', srv_rows)
    out.append('')
    act_rows = [f'"{a[0]}/action/{a[1]}" => {a[0]}::action::{a[1]};' for a in sorted(actions, key=lambda a: a[:2])]
    out += macro('for_each_action', 'Calls `$callback! { "pkg/action/Name" => pkg::action::Name; ... }` with every action here.', act_rows)
    out.append('')
    const_rows = [f'"{m.ros_name}" "{c[0]}" {"::".join(m.path)}::{c[0]};' for m in all_msgs for c in m.constants]
    out += macro('for_each_constant', 'Calls `$callback! { "pkg/kind/Name" "NAME" pkg::kind::Name::NAME; ... }` with every constant here.', const_rows)
    return '\n'.join(out) + '\n'


def to_ros(f):
    n = rust_field(f.name)
    if f.nested and f.array:
        return f'{n}: self.{n}.into_iter().map(RosMirror::into_ros).collect()'
    if f.nested:
        return f'{n}: self.{n}.into_ros()'
    return f'{n}: self.{n}'


def from_ros(f):
    n = rust_field(f.name)
    if f.nested and f.array:
        return f'{n}: ros.{n}.into_iter().map(RosMirror::from_ros).collect()'
    if f.nested:
        return f'{n}: RosMirror::from_ros(ros.{n})'
    return f'{n}: ros.{n}'


def mirror(all_msgs, services, actions):
    out = [HEADER.rstrip('\n'), '', 'use crate::{ActionMirror, RosMirror, ServiceMirror};', '']
    for m in all_msgs:
        path = '::'.join(m.path)
        plain, ros = f'mower_msgs::{path}', f'r2r::{path}'
        if m.fields:
            up = ', '.join(to_ros(f) for f in m.fields)
            down = ', '.join(from_ros(f) for f in m.fields)
            args = ('self', 'ros')
        else:
            up, down = '', ''
            args = ('self', '_ros')
        out += [f'impl RosMirror for {plain} {{',
                f'    type Ros = {ros};',
                f'    fn into_ros({args[0]}) -> {ros} {{ {ros} {{ {up} }} }}',
                f'    fn from_ros({args[1]}: {ros}) -> Self {{ Self {{ {down} }} }}',
                '}']
    for p, n, _ in sorted(services, key=lambda s: s[:2]):
        out += [f'impl ServiceMirror for mower_msgs::{p}::srv::{n}::Service {{ type Ros = r2r::{p}::srv::{n}::Service; }}']
    for a in sorted(actions, key=lambda a: a[:2]):
        p, n = a[0], a[1]
        out += [f'impl ActionMirror for mower_msgs::{p}::action::{n}::Action {{ type Ros = r2r::{p}::action::{n}::Action; }}']
    return '\n'.join(out) + '\n'


def outputs():
    msgs, services, actions = load()
    pkgs = sorted({m.path[0] for m in msgs} | {s[0] for s in services} | {a[0] for a in actions})
    files = {}
    for pkg in pkgs:
        files[os.path.join(PLAIN, pkg + '.rs')] = plain_package(
            pkg, [m for m in msgs if m.path[0] == pkg], [s for s in services if s[0] == pkg], [a for a in actions if a[0] == pkg])
    all_msgs = every_message(msgs, services, actions)
    files[os.path.join(PLAIN, 'mod.rs')] = plain_mod(pkgs, all_msgs, services, actions)
    files[MIRROR] = mirror(all_msgs, services, actions)
    return files, len(all_msgs), len(services), len(actions)


def main():
    files, n_msgs, n_srv, n_act = outputs()
    if '--check' in sys.argv[1:]:
        stale = [p for p, text in files.items() if not os.path.exists(p) or read(p) != text]
        known = set(files)
        stale += [os.path.join(PLAIN, f) for f in os.listdir(PLAIN) if os.path.join(PLAIN, f) not in known]
        if stale:
            raise SystemExit('stale, gen_types.py rewrites them:\n  ' + '\n  '.join(stale))
        print(f'{n_msgs} message types, {n_srv} services, {n_act} actions: the generated code is current')
        return
    os.makedirs(PLAIN, exist_ok=True)
    for path, text in files.items():
        with open(path, 'w', encoding='utf-8') as f:
            f.write(text)
    print(f'{n_msgs} message types, {n_srv} services, {n_act} actions')


if __name__ == '__main__':
    main()
