#!/usr/bin/env python3
"""Second half of boot_generate.sh: the vectors that come from Python.

    boot_vectors.py LAYOUT_JSON MOWER_FLASH_PY OUT_DIR

* boot_oracle.json  = the C oracle's layout (LAYOUT_JSON) + CRC-32 vectors
  from zlib, which is what the bootloader's BlFlash_Crc32 and
  mower_flash.py's image CRC both are, + what mower_flash.py itself mirrors
  of boot_shared.h (its constants, the frames it builds, how it decodes the
  C-packed BL_INFO / BL_ACK bytes).
* pop_frame_oracle.json = byte streams cut into random reads, and the frames
  the original FrameReader._pop_frame of firmware/tools/mower_flash.py pops
  after each read (and how many bytes it keeps), for the parser the Rust
  flasher reads with (protocol::FrameParser).

Deterministic: a fixed seed, so a rerun gives the same files.
"""

import importlib.util
import json
import os
import random
import sys
import types
import zlib


def load_mower_flash(path):
    # mower_flash.py needs pyserial only to open a port; _pop_frame never does.
    # No __pycache__ next to the firmware tools.
    sys.dont_write_bytecode = True
    stub = types.ModuleType("serial")
    stub.Serial = object
    sys.modules.setdefault("serial", stub)
    spec = importlib.util.spec_from_file_location("mower_flash", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def crc_vectors(rng):
    datas = [
        b"",
        b"\x00",
        b"\xff",
        b"123456789",
        b"\x00" * 32,
        b"\xff" * 32,
        bytes(range(256)),
        bytes(rng.randrange(256) for _ in range(1000)),
        bytes(rng.randrange(256) for _ in range(4097)),
        bytes.fromhex("a55a0112010884000000"),
    ]
    out = [{"data": d.hex(), "crc": zlib.crc32(d) & 0xFFFFFFFF} for d in datas]
    # long runs, generated by the test rather than stored
    fills = [
        {"fill": f, "len": n, "crc": zlib.crc32(bytes([f]) * n) & 0xFFFFFFFF}
        for f, n in ((0xFF, 16384), (0xFF, 360448), (0x00, 65536), (0x5A, 46440))
    ]
    return out, fills


def python_side(mf, layout):
    """mower_flash.py's own copy of the protocol, to pin the Rust one to it."""
    import struct

    consts = {
        name: getattr(mf, name)
        for name in (
            "SOF0", "SOF1", "VERSION", "T_ENTER_BOOTLOADER", "T_ENTER_BOOTLOADER_ACK",
            "T_BL_PING", "T_BL_ERASE", "T_BL_WRITE", "T_BL_VERIFY", "T_BL_RUN_APP",
            "T_BL_INFO", "T_BL_ACK", "T_INFO_REQUEST", "T_FIRMWARE_INFO",
            "BOOT_REQUEST_MAGIC", "APP_START_ADDRESS", "APP_MAX_SIZE", "WRITE_CHUNK_MAX",
            "INFO_FLAG_APP_VALID", "INFO_FLAG_ENTERED_BY_REQUEST", "INFO_FLAG_ERASED",
        )
    }
    frames = []
    for seq in (1, 0x7F, 0xFF):
        # the same expressions as Bootloader.send's callers in mower_flash.py
        frames += [
            {"fn": "ping", "args": [seq], "bytes": mf.build_frame(mf.T_BL_PING, seq).hex()},
            {"fn": "run_app", "args": [seq], "bytes": mf.build_frame(mf.T_BL_RUN_APP, seq, b"").hex()},
            {"fn": "enter_bootloader", "args": [seq], "bytes": mf.build_frame(
                mf.T_ENTER_BOOTLOADER, seq, struct.pack("<II", mf.BOOT_REQUEST_MAGIC, 0)).hex()},
            {"fn": "info_request", "args": [seq], "bytes": mf.build_frame(mf.T_INFO_REQUEST, seq).hex()},
        ]
        for size in (4, 46440, mf.APP_MAX_SIZE):
            frames.append({"fn": "erase", "args": [seq, size],
                           "bytes": mf.build_frame(mf.T_BL_ERASE, seq, struct.pack("<I", size)).hex()})
            frames.append({"fn": "verify", "args": [seq, size, 0x0178F726], "bytes": mf.build_frame(
                mf.T_BL_VERIFY, seq, struct.pack("<II", size, 0x0178F726)).hex()})
        for off, n in ((0, 128), (0x80, 128), (0x57F80, 128), (0xB500, 104), (0, 4)):
            data = bytes((off + i * 7) & 0xFF for i in range(n))
            frames.append({"fn": "write", "args": [seq, off, data.hex()], "bytes": mf.build_frame(
                mf.T_BL_WRITE, seq, struct.pack("<I", off) + data).hex()})
    infos = []
    acks = []
    for p in layout["packed"]:
        raw = bytes.fromhex(p["bytes"])
        if p["struct"] == "boot_info_payload_t":
            infos.append({"bytes": p["bytes"], "parse_info": mf.parse_info(raw)})
        elif p["struct"] == "boot_ack_payload_t":
            acks.append({"bytes": p["bytes"], "unpack": list(struct.unpack("<BBI", raw))})
    status_names = {str(k): v for k, v in mf.STATUS_NAMES.items()}
    return {"constants": consts, "host_frames": frames, "parse_info": infos,
            "ack_unpack": acks, "status_names": status_names}


def frame(mf, ftype, seq, payload):
    return bytearray(mf.build_frame(ftype, seq, payload))


def stream(mf, rng):
    """One byte stream: valid frames mixed with every way a frame goes bad."""
    out = bytearray()
    types_ = [0x10, 0x11, 0x12, 0x13, 0x14, 0x90, 0x91, 0x8F, 0x81, 0x85, 0x87]
    for _ in range(rng.randrange(4, 16)):
        kind = rng.choices(
            ["frame", "badcrc", "badver", "junk", "cut", "sofpair", "longlen", "nested"],
            weights=[10, 2, 1, 3, 1, 1, 1, 1],
        )[0]
        ftype = rng.choice(types_ + [rng.randrange(256)])
        seq = rng.randrange(256)
        plen = rng.choice([0, 1, 4, 6, 8, 12, 16, rng.randrange(0, 41)])
        payload = bytes(rng.randrange(256) for _ in range(plen))
        f = frame(mf, ftype, seq, payload)
        if kind == "frame":
            out += f
        elif kind == "badcrc":
            f[-1 - rng.randrange(2)] ^= 1 << rng.randrange(8)
            out += f
        elif kind == "badver":
            body = bytes([0x02, ftype, seq, plen]) + payload
            crc = mf.crc16_ccitt(body)
            out += bytes([0xA5, 0x5A]) + body + bytes([crc & 0xFF, crc >> 8])
        elif kind == "junk":
            out += bytes(rng.choice([0xA5, 0x5A, 0x00, 0xFF, rng.randrange(256)])
                         for _ in range(rng.randrange(1, 12)))
        elif kind == "cut":
            out += f[: rng.randrange(1, len(f))]
        elif kind == "sofpair":
            out += bytes([0xA5, 0xA5, 0x5A]) if rng.random() < 0.5 else bytes([0xA5])
        elif kind == "longlen":
            # a false SOF whose length byte makes the parser wait for more
            out += bytes([0xA5, 0x5A, 0x01, ftype, seq, rng.choice([0x40, 0x80, 0xFF])])
        elif kind == "nested":
            # a real frame inside a corrupt one's payload
            inner = frame(mf, 0x91, seq, bytes([0x12, 0, 0x80, 0, 0, 0]))
            outer = frame(mf, ftype, seq, bytes(inner))
            outer[-1] ^= 0xFF
            out += outer
    if rng.random() < 0.3:
        out += bytes([0xA5])  # a SOF0 cut off at the end of the stream
    return bytes(out)


def pop_vectors(mf, rng, cases=80):
    out = []
    for _ in range(cases):
        data = stream(mf, rng)
        chunks = []
        i = 0
        while i < len(data):
            n = rng.choice([1, 2, 3, 7, 14, 32, 64, rng.randrange(1, 300)])
            chunks.append(data[i : i + n])
            i += n
        reader = mf.FrameReader(None)
        reads = []
        for chunk in chunks:
            reader.buf.extend(chunk)
            frames = []
            while True:
                f = reader._pop_frame()
                if f is None:
                    break
                frames.append([f[0], f[1], f[2].hex()])
            reads.append({"data": chunk.hex(), "frames": frames, "left": len(reader.buf)})
        out.append(reads)
    return out


def main():
    layout_path, mower_flash_py, out_dir = sys.argv[1:4]
    rng = random.Random(20261030)
    mf = load_mower_flash(mower_flash_py)
    with open(layout_path) as f:
        layout = json.load(f)
    crc, fills = crc_vectors(rng)
    layout["crc32"] = crc
    layout["crc32_fill"] = fills
    layout["python"] = python_side(mf, layout)
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "boot_oracle.json"), "w") as f:
        json.dump(layout, f, indent=1)
        f.write("\n")
    with open(os.path.join(out_dir, "pop_frame_oracle.json"), "w") as f:
        json.dump({"source": "firmware/tools/mower_flash.py FrameReader._pop_frame",
                   "cases": pop_vectors(mf, rng)}, f, separators=(",", ":"))
        f.write("\n")


if __name__ == "__main__":
    main()
