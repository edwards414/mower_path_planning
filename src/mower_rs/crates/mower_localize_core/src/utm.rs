//! The UTM projection, ported from GeographicLib 2.3 (`TransverseMercator.cpp`,
//! `UTMUPS.cpp`, `Math.cpp`) — the same library and version that
//! `navsat_transform` links against, via `navsat_conversions.hpp`.
//!
//! Only the UTM branch is ported; the polar UPS branch returns an error (this
//! robot mows lawns, not ice shelves). See the crate README.

// The shapes below are GeographicLib's, kept as-is so the port reads against
// the C++: `!(x >= y)` is its NaN-safe guard, and the MGRS tile arithmetic is
// spelled out the way UTMUPS.cpp spells it.
#![allow(clippy::neg_cmp_op_on_partial_ord)]
#![allow(clippy::identity_op)]
#![allow(clippy::manual_range_contains)]

const MAXPOW: usize = 6;
const QD: f64 = 90.0;
const HD: f64 = 180.0;
const TD: f64 = 360.0;
const DEGREE: f64 = std::f64::consts::PI / 180.0;

const WGS84_A: f64 = 6378137.0;
const UTM_K0: f64 = 0.9996;
const TILE: f64 = 100_000.0;

fn wgs84_f() -> f64 {
    // Constants::WGS84_f(): 1 / (298257223563 / 1e9).
    1.0 / (298_257_223_563f64 / 1_000_000_000.0)
}

/// IEEE-754 `remainder(x, y)`: x - n*y with n the nearest integer to x/y,
/// ties to even.
fn remainder(x: f64, y: f64) -> f64 {
    let q = x / y;
    let mut n = q.round();
    // round() is ties-away-from-zero; fix up exact halves to ties-to-even.
    if (q - q.trunc()).abs() == 0.5 && n % 2.0 != 0.0 {
        n -= q.signum();
    }
    x - n * y
}

/// `Math::AngNormalize`.
fn ang_normalize(x: f64) -> f64 {
    let y = remainder(x, TD);
    if y.abs() == HD {
        HD.copysign(x)
    } else {
        y
    }
}

/// `Math::sum` (the exact two-sum).
fn two_sum(u: f64, v: f64) -> (f64, f64) {
    let s = u + v;
    let mut up = s - v;
    let mut vpp = s - up;
    up -= u;
    vpp -= v;
    let t = if s != 0.0 { -(up + vpp) } else { s };
    (s, t)
}

/// `Math::AngDiff`.
fn ang_diff(x: f64, y: f64) -> f64 {
    let (mut d, mut e) = two_sum(remainder(-x, TD), remainder(y, TD));
    let r = two_sum(remainder(d, TD), e);
    d = r.0;
    e = r.1;
    if d == 0.0 || d.abs() == HD {
        d = d.copysign(if e == 0.0 { y - x } else { -e });
    }
    d
}

/// `Math::LatFix`.
fn lat_fix(x: f64) -> f64 {
    if x.abs() > QD {
        f64::NAN
    } else {
        x
    }
}

/// `Math::sincosd`, which reduces the argument exactly before converting.
fn sincosd(x: f64) -> (f64, f64) {
    let q = x / QD;
    let mut n = q.round();
    if (q - q.trunc()).abs() == 0.5 && n % 2.0 != 0.0 {
        n -= q.signum();
    }
    let r = (x - n * QD) * DEGREE;
    let s = r.sin();
    let c = r.cos();
    let quadrant = (((n as i64) % 4) + 4) % 4;
    let (mut sinx, cosx) = match quadrant {
        0 => (s, c),
        1 => (c, -s),
        2 => (-s, -c),
        _ => (-c, s),
    };
    if sinx == 0.0 {
        sinx = sinx.copysign(x);
    }
    (sinx, cosx)
}

/// `Math::atan2d`.
fn atan2d(y: f64, x: f64) -> f64 {
    let (mut x, mut y) = (x, y);
    let mut q = 0;
    if y.abs() > x.abs() {
        std::mem::swap(&mut x, &mut y);
        q = 2;
    }
    if x.is_sign_negative() {
        x = -x;
        q += 1;
    }
    let ang = y.atan2(x) / DEGREE;
    match q {
        1 => HD.copysign(y) - ang,
        2 => QD - ang,
        3 => -QD + ang,
        _ => ang,
    }
}

fn atand(x: f64) -> f64 {
    atan2d(x, 1.0)
}

/// `Math::eatanhe`.
fn eatanhe(x: f64, es: f64) -> f64 {
    if es > 0.0 {
        es * (es * x).atanh()
    } else {
        -es * (es * x).atan()
    }
}

/// `Math::taupf`.
fn taupf(tau: f64, es: f64) -> f64 {
    if tau.is_finite() {
        let tau1 = 1.0f64.hypot(tau);
        let sig = eatanhe(tau / tau1, es).sinh();
        1.0f64.hypot(sig) * tau - sig * tau1
    } else {
        tau
    }
}

/// `Math::tauf` (Newton's method, at most 5 iterations).
fn tauf(taup: f64, es: f64) -> f64 {
    let tol = f64::EPSILON.sqrt() / 10.0;
    let taumax = 2.0 / f64::EPSILON.sqrt();
    let e2m = 1.0 - es * es;
    let mut tau = if taup.abs() > 70.0 {
        taup * eatanhe(1.0, es).exp()
    } else {
        taup / e2m
    };
    let stol = tol * 1.0f64.max(taup.abs());
    if !(tau.abs() < taumax) {
        return tau;
    }
    for _ in 0..5 {
        let taupa = taupf(tau, es);
        let dtau = (taup - taupa) * (1.0 + e2m * tau * tau)
            / (e2m * 1.0f64.hypot(tau) * 1.0f64.hypot(taupa));
        tau += dtau;
        if !(dtau.abs() >= stol) {
            break;
        }
    }
    tau
}

/// `Math::polyval`.
fn polyval(n: i32, p: &[f64], off: usize, x: f64) -> f64 {
    let mut i = 0usize;
    let mut y = if n < 0 { 0.0 } else { p[off + i] };
    let mut n = n;
    while n > 0 {
        n -= 1;
        i += 1;
        y = y * x + p[off + i];
    }
    y
}

