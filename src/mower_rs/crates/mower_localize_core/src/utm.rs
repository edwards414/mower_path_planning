/// `GeographicLib::TransverseMercator` (the Krüger series, order 6).
#[derive(Clone, Debug)]
pub struct TransverseMercator {
    #[allow(dead_code)]
    a: f64,
    k0: f64,
    es: f64,
    e2m: f64,
    e2: f64,
    c: f64,
    a1: f64,
    b1: f64,
    alp: [f64; MAXPOW + 1],
    bet: [f64; MAXPOW + 1],
}

impl TransverseMercator {
    pub fn new(a: f64, f: f64, k0: f64) -> Self {
        let e2 = f * (2.0 - f);
        let es = (if f < 0.0 { -1.0 } else { 1.0 }) * e2.abs().sqrt();
        let e2m = 1.0 - e2;
        let c = e2m.sqrt() * eatanhe(1.0, es).exp();
        let n = f / (2.0 - f);

        let m = (MAXPOW / 2) as i32;
        let b1 = polyval(m, &B1COEFF, 0, n * n) / (B1COEFF[m as usize + 1] * (1.0 + n));
        let a1 = b1 * a;

        let mut alp = [0.0f64; MAXPOW + 1];
        let mut bet = [0.0f64; MAXPOW + 1];
        let mut o = 0usize;
        let mut d = n;
        for l in 1..=MAXPOW {
            let m = (MAXPOW - l) as i32;
            alp[l] = d * polyval(m, &ALPCOEFF, o, n) / ALPCOEFF[o + m as usize + 1];
            bet[l] = d * polyval(m, &BETCOEFF, o, n) / BETCOEFF[o + m as usize + 1];
            o += m as usize + 2;
            d *= n;
        }

        Self {
            a,
            k0,
            es,
            e2m,
            e2,
            c,
            a1,
            b1,
            alp,
            bet,
        }
    }

    /// `TransverseMercator::UTM()`.
    pub fn utm() -> Self {
        Self::new(WGS84_A, wgs84_f(), UTM_K0)
    }

    /// `TransverseMercator::Forward`. Returns (x, y, gamma, k).
    pub fn forward(&self, lon0: f64, lat: f64, lon: f64) -> (f64, f64, f64, f64) {
        let mut lat = lat_fix(lat);
        let mut lon = ang_diff(lon0, lon);
        let mut latsign = if lat.is_sign_negative() { -1.0 } else { 1.0 };
        let lonsign = if lon.is_sign_negative() { -1.0 } else { 1.0 };
        lon *= lonsign;
        lat *= latsign;
        let backside = lon > QD;
        if backside {
            if lat == 0.0 {
                latsign = -1.0;
            }
            lon = HD - lon;
        }
        let (sphi, cphi) = sincosd(lat);
        let (slam, clam) = sincosd(lon);

        let (xip, etap, mut gamma, mut k);
        if lat != QD {
            let tau = sphi / cphi;
            let taup = taupf(tau, self.es);
            xip = taup.atan2(clam);
            etap = (slam / taup.hypot(clam)).asinh();
            gamma = atan2d(slam * taup, clam * 1.0f64.hypot(taup));
            k = (self.e2m + self.e2 * cphi * cphi).sqrt() * 1.0f64.hypot(tau) / taup.hypot(clam);
        } else {
            xip = std::f64::consts::PI / 2.0;
            etap = 0.0;
            gamma = lon;
            k = self.c;
        }

        let c0 = (2.0 * xip).cos();
        let ch0 = (2.0 * etap).cosh();
        let s0 = (2.0 * xip).sin();
        let sh0 = (2.0 * etap).sinh();
        let mut a = Complex::new(2.0 * c0 * ch0, -2.0 * s0 * sh0);
        let mut n = MAXPOW;
        let mut y0 = if n & 1 == 1 {
            Complex::new(self.alp[n], 0.0)
        } else {
            Complex::zero()
        };
        let mut y1 = Complex::zero();
        let mut z0 = if n & 1 == 1 {
            Complex::new(2.0 * n as f64 * self.alp[n], 0.0)
        } else {
            Complex::zero()
        };
        let mut z1 = Complex::zero();
        if n & 1 == 1 {
            n -= 1;
        }
        while n != 0 {
            y1 = a.mul(&y0).sub(&y1).add_re(self.alp[n]);
            z1 = a.mul(&z0).sub(&z1).add_re(2.0 * n as f64 * self.alp[n]);
            n -= 1;
            y0 = a.mul(&y1).sub(&y0).add_re(self.alp[n]);
            z0 = a.mul(&z1).sub(&z0).add_re(2.0 * n as f64 * self.alp[n]);
            n -= 1;
        }
        a = a.scale(0.5);
        z1 = Complex::new(1.0, 0.0).sub(&z1).add(&a.mul(&z0));
        a = Complex::new(s0 * ch0, c0 * sh0);
        y1 = Complex::new(xip, etap).add(&a.mul(&y0));

        gamma -= atan2d(z1.im, z1.re);
        k *= self.b1 * z1.abs();
        let xi = y1.re;
        let eta = y1.im;
        let y = self.a1
            * self.k0
            * (if backside {
                std::f64::consts::PI - xi
            } else {
                xi
            })
            * latsign;
        let x = self.a1 * self.k0 * eta * lonsign;
        if backside {
            gamma = HD - gamma;
        }
        gamma *= latsign * lonsign;
        gamma = ang_normalize(gamma);
        k *= self.k0;
        (x, y, gamma, k)
    }

    /// `TransverseMercator::Reverse`. Returns (lat, lon, gamma, k).
    pub fn reverse(&self, lon0: f64, x: f64, y: f64) -> (f64, f64, f64, f64) {
        let mut xi = y / (self.a1 * self.k0);
        let mut eta = x / (self.a1 * self.k0);
        let xisign = if xi.is_sign_negative() { -1.0 } else { 1.0 };
        let etasign = if eta.is_sign_negative() { -1.0 } else { 1.0 };
        xi *= xisign;
        eta *= etasign;
        let backside = xi > std::f64::consts::PI / 2.0;
        if backside {
            xi = std::f64::consts::PI - xi;
        }
        let c0 = (2.0 * xi).cos();
        let ch0 = (2.0 * eta).cosh();
        let s0 = (2.0 * xi).sin();
        let sh0 = (2.0 * eta).sinh();
        let mut a = Complex::new(2.0 * c0 * ch0, -2.0 * s0 * sh0);
        let mut n = MAXPOW;
        let mut y0 = if n & 1 == 1 {
            Complex::new(-self.bet[n], 0.0)
        } else {
            Complex::zero()
        };
        let mut y1 = Complex::zero();
        let mut z0 = if n & 1 == 1 {
            Complex::new(-2.0 * n as f64 * self.bet[n], 0.0)
        } else {
            Complex::zero()
        };
        let mut z1 = Complex::zero();
        if n & 1 == 1 {
            n -= 1;
        }
        while n != 0 {
            y1 = a.mul(&y0).sub(&y1).add_re(-self.bet[n]);
            z1 = a.mul(&z0).sub(&z1).add_re(-2.0 * n as f64 * self.bet[n]);
            n -= 1;
            y0 = a.mul(&y1).sub(&y0).add_re(-self.bet[n]);
            z0 = a.mul(&z1).sub(&z0).add_re(-2.0 * n as f64 * self.bet[n]);
            n -= 1;
        }
        a = a.scale(0.5);
        z1 = Complex::new(1.0, 0.0).sub(&z1).add(&a.mul(&z0));
        a = Complex::new(s0 * ch0, c0 * sh0);
        y1 = Complex::new(xi, eta).add(&a.mul(&y0));

        let mut gamma = atan2d(z1.im, z1.re);
        let mut k = self.b1 / z1.abs();
        let xip = y1.re;
        let etap = y1.im;
        let s = etap.sinh();
        let c = 0.0f64.max(xip.cos());
        let r = s.hypot(c);
        let (mut lat, mut lon);
        if r != 0.0 {
            lon = atan2d(s, c);
            let sxip = xip.sin();
            let tau = tauf(sxip / r, self.es);
            gamma += atan2d(sxip * etap.tanh(), c);
            lat = atand(tau);
            k *= (self.e2m + self.e2 / (1.0 + tau * tau)).sqrt() * 1.0f64.hypot(tau) * r;
        } else {
            lat = QD;
            lon = 0.0;
            k *= self.c;
        }
        lat *= xisign;
        if backside {
            lon = HD - lon;
        }
        lon *= etasign;
        lon = ang_normalize(lon + lon0);
        if backside {
            gamma = HD - gamma;
        }
        gamma *= xisign * etasign;
        gamma = ang_normalize(gamma);
        k *= self.k0;
        (lat, lon, gamma, k)
    }
}

#[derive(Clone, Copy, Debug)]
struct Complex {
    re: f64,
    im: f64,
}

impl Complex {
    fn new(re: f64, im: f64) -> Self {
        Self { re, im }
    }
    fn zero() -> Self {
        Self::new(0.0, 0.0)
    }
    fn mul(&self, o: &Complex) -> Complex {
        Complex::new(
            self.re * o.re - self.im * o.im,
            self.re * o.im + self.im * o.re,
        )
    }
    fn add(&self, o: &Complex) -> Complex {
        Complex::new(self.re + o.re, self.im + o.im)
    }
    fn sub(&self, o: &Complex) -> Complex {
        Complex::new(self.re - o.re, self.im - o.im)
    }
    fn add_re(&self, v: f64) -> Complex {
        Complex::new(self.re + v, self.im)
    }
    fn scale(&self, s: f64) -> Complex {
        Complex::new(self.re * s, self.im * s)
    }
    fn abs(&self) -> f64 {
        self.re.hypot(self.im)
    }
}

/// `UTMUPS::StandardZone`'s special values.
pub const ZONE_UPS: i32 = 0;
pub const ZONE_STANDARD: i32 = -1;
pub const ZONE_INVALID: i32 = -4;

/// `MGRS::LatitudeBand`.
fn latitude_band(lat: f64) -> i32 {
    let ilat = lat.floor() as i32;
    (-10).max(9.min((ilat + 80) / 8 - 10))
}

/// `UTMUPS::CentralMeridian`.
pub fn central_meridian(zone: i32) -> f64 {
    (6 * zone - 183) as f64
}

/// `UTMUPS::StandardZone`.
pub fn standard_zone(lat: f64, lon: f64, setzone: i32) -> i32 {
    // MINZONE is 0 (== UPS), so any non-negative setzone is taken as given.
    if setzone >= 0 || setzone == ZONE_INVALID {
        return setzone;
    }
    if lat.is_nan() || lon.is_nan() {
        return ZONE_INVALID;
    }
    if setzone == -2 || (lat >= -80.0 && lat < 84.0) {
        let mut ilon = ang_normalize(lon).floor() as i32;
        if ilon == 180 {
            ilon = -180;
        }
        let mut zone = (ilon + 186) / 6;
        let band = latitude_band(lat);
        if band == 7 && zone == 31 && ilon >= 3 {
            zone = 32;
        } else if band == 9 && (0..42).contains(&ilon) {
            zone = 2 * ((ilon + 183) / 12) + 1;
        }
        zone
    } else {
        ZONE_UPS
    }
}

#[derive(Debug, PartialEq, Eq)]
pub enum UtmError {
    LatitudeOutOfRange,
    PolarRegionUnsupported,
    LongitudeTooFarFromZone,
    CoordinatesOutOfRange,
    BadZone,
}

/// Easting/northing offsets and limits for the UTM half of `UTMUPS`.
fn false_easting() -> f64 {
    5.0 * TILE
}

fn false_northing(northp: bool) -> f64 {
    if northp {
        0.0
    } else {
        100.0 * TILE
    }
}

fn check_coords(northp: bool, x: f64, y: f64) -> bool {
    let slop = TILE;
    let min_easting = 1.0 * TILE;
    let max_easting = 9.0 * TILE;
    let (min_northing, max_northing) = if northp {
        ((0 + 10 - 100) as f64 * TILE, 95.0 * TILE)
    } else {
        (10.0 * TILE, (100 + 95 - 0) as f64 * TILE)
    };
    !(x < min_easting - slop
        || x > max_easting + slop
        || y < min_northing - slop
        || y > max_northing + slop)
}

/// `UTMUPS::Forward` restricted to UTM. Returns (zone, northp, x, y, gamma, k).
pub fn utmups_forward(
    lat: f64,
    lon: f64,
    setzone: i32,
) -> Result<(i32, bool, f64, f64, f64, f64), UtmError> {
    if lat.abs() > QD {
        return Err(UtmError::LatitudeOutOfRange);
    }
    let northp = !lat.is_sign_negative();
    let zone = standard_zone(lat, lon, setzone);
    if zone == ZONE_INVALID {
        return Err(UtmError::BadZone);
    }
    if zone == ZONE_UPS {
        return Err(UtmError::PolarRegionUnsupported);
    }
    let lon0 = central_meridian(zone);
    let dlon = ang_diff(lon0, lon);
    if !(dlon <= 60.0) {
        return Err(UtmError::LongitudeTooFarFromZone);
    }
    let (mut x, mut y, gamma, k) = TransverseMercator::utm().forward(lon0, lat, lon);
    x += false_easting();
    y += false_northing(northp);
    if !check_coords(northp, x, y) {
        return Err(UtmError::CoordinatesOutOfRange);
    }
    Ok((zone, northp, x, y, gamma, k))
}

/// `UTMUPS::Reverse` restricted to UTM. Returns (lat, lon, gamma, k).
pub fn utmups_reverse(
    zone: i32,
    northp: bool,
    x: f64,
    y: f64,
) -> Result<(f64, f64, f64, f64), UtmError> {
    if !(1..=60).contains(&zone) {
        return Err(UtmError::BadZone);
    }
    let x = x - false_easting();
    let y = y - false_northing(northp);
    Ok(TransverseMercator::utm().reverse(central_meridian(zone), x, y))
}
